import { describe, expect, test } from "vitest";
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { loadFrozenCorpus, runCorpusPass } from "../../benchmark/model-payloads.js";

const plugin = resolve(import.meta.dirname, "../..");
describe("frozen synthetic model payload corpus", () => {
  test("pins source bytes, independent expected arithmetic and the actual starting revision", () => {
    const { corpus, manifest } = loadFrozenCorpus();
    expect(manifest.baselineRevision).toBe("e0ad0de2eecf1d1334c876304d1eeb4f35a5c1a4");
    expect(manifest.expectedDerivation).toContain("No expected value is generated by the accounting implementation");
    expect(corpus.scenarios.map((scenario: any) => scenario.id)).toEqual([
      "broad-retrieval", "overlapping-queries", "changed-source-reread", "long-ci-wait", "independent-review", "bounded-stats",
    ]);
    expect(corpus.responseFixtures.map((row: any) => row.expectedBytes)).toEqual([14, 30, 61, 137, null]);
    expect(corpus.counterScenarios.find((row: any) => row.id === "historical-reset-gap")).toMatchObject({ expectedInput: 16, expectedOutput: 14, expectedCoverage: "partial" });
    expect(corpus.counterSpecials).toHaveLength(6);
    expect(corpus.scenarios.find((row: any) => row.id === "long-ci-wait").states.at(-1).simulatedElapsedMs).toBe(600000);
  });
  test("detects corpus edits instead of regenerating expectations from production code", () => {
    const root = mkdtempSync(join(tmpdir(), "corpus-drift-"));
    try {
      for (const name of ["model-payloads.json", "model-payloads.manifest.json"]) {
        copyFileSync(join(plugin, "benchmark/fixtures", name), join(root, name));
      }
      writeFileSync(join(root, "model-payloads.json"), readFileSync(join(root, "model-payloads.json"), "utf8") + " ");
      expect(() => loadFrozenCorpus(root)).toThrow("corpus differs from frozen digest");
    } finally { rmSync(root, { recursive: true, force: true }); }
  });
  test("replays quality twice in isolated state and includes every overflow request/envelope", () => {
    const first = runCorpusPass(plugin), second = runCorpusPass(plugin);
    expect(first.corpusSha256).toBe(second.corpusSha256);
    expect(first.inputFileSha256).toEqual(second.inputFileSha256);
    expect(first.environment).toEqual(second.environment);
    expect(first.isolation).toEqual({ credentialsInherited: false, stateShared: false, liveSessionReads: false, temporaryStateRemoved: true });
    expect(first.counters).toEqual(second.counters); expect(first.counters.supported).toBe(true);
    expect(first.counters.results).toHaveLength(9);
    expect(first.responseCoverage).toEqual(second.responseCoverage);
    expect(first.responseCoverage.at(-1)).toMatchObject({ independentlyObservedBytes: null, accounting: "partial", supported: true });
    for (const report of [first, second]) {
      expect(report.accountQuotaTokens).toBeNull();
      expect(report.cases.every((row: any) => row.quality === "complete" && row.missingFindings.length === 0)).toBe(true);
      for (const row of report.cases) {
        const requests = row.observations.reduce((sum: number, call: any) => sum + call.requestBytes, 0);
        const knownReturned = row.observations.reduce((sum: number, call: any) => sum + (call.responseBytes ?? 0), 0);
        expect(row.requestBytes).toBe(requests); expect(row.knownReturnedBytes).toBe(knownReturned);
        expect(row.knownTotalVisibleBytes).toBe(requests + knownReturned + row.descriptionBytes);
        if (row.observations.some((call: any) => call.responseBytes === null)) expect(row.totalVisibleBytes).toBeNull();
      }
      for (const name of ["long-ci-wait", "independent-review", "bounded-stats"]) {
        const row = report.cases.find((row: any) => row.id === name);
        expect(row.overflowCalls).toBeGreaterThan(0);
        expect(row.overflowRequestBytes).toBeGreaterThan(0); expect(row.overflowResponseBytes).toBeGreaterThan(0);
      }
    }
    // Runtime-generated references/timing can alter bytes; correctness and
    // independent arithmetic must repeat without asserting artificial timing.
    expect(first.cases.map((row: any) => [row.id, row.quality, row.missingFindings]))
      .toEqual(second.cases.map((row: any) => [row.id, row.quality, row.missingFindings]));
  }, 30_000);
});
